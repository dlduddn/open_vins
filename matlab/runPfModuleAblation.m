function variants = forwardSelectionVariants()
    variants = struct('name', {}, 'stage', {}, 'description', {}, 'moduleSet', {}, 'params', {});
    base = pfMinimalParams();

    variants(end + 1) = variant("fwd_00_minimal", "forward", ...
        "Forward-selection start: odometry propagation only", ...
        "minimal", base);

    params = mergeStructs(base, pfStabilizationParams());
    variants(end + 1) = variant("fwd_01_pf_stabilization", "forward", ...
        "Add stabilized PF process model while still propagation-only", ...
        "minimal + PF stabilization", params);

    params = mergeStructs(base, pfStabilizationParams(), measurementMinimalParams());
    variants(end + 1) = variant("fwd_02_measurement_basic", "forward", ...
        "Add measurement update with query/map gates disabled", ...
        "prev + measurement", params);

    params = mergeStructs(params, struct('assocUseCurveMapCorrespondenceRule', true));
    variants(end + 1) = variant("fwd_03_curve_correspondence", "forward", ...
        "Add curve-map correspondence requirement", ...
        "prev + curve correspondence", params);

    params = mergeStructs(params, struct('assocUseBodyRoadGate', true));
    variants(end + 1) = variant("fwd_04_body_road_gate", "forward", ...
        "Add body-road-width gate", ...
        "prev + body road gate", params);

    params = mergeStructs(params, robustLikelihoodParams());
    variants(end + 1) = variant("fwd_05_robust_likelihood", "forward", ...
        "Add robust residual model and penalties", ...
        "prev + robust likelihood", params);

    params = mergeStructs(params, likelihoodStabilizationParams());
    variants(end + 1) = variant("fwd_06_likelihood_stabilization", "forward", ...
        "Add likelihood temperature, clipping, and uniform mix", ...
        "prev + likelihood stabilization", params);

    params = mergeStructs(params, queryRuleParams());
    variants(end + 1) = variant("fwd_07_query_rules", "forward", ...
        "Add query-only yaw/pitch/chord/body filters", ...
        "prev + query rules", params);

    params = mergeStructs(params, struct('assocUseCameraFovGate', true));
    variants(end + 1) = variant("fwd_08_camera_fov_gate", "forward", ...
        "Add camera FOV gate", ...
        "prev + FOV gate", params);

    params = mergeStructs(params, initAlignmentParams());
    variants(end + 1) = variant("fwd_09_trajectory_init", "forward", ...
        "Add trajectory initial alignment as PF initial state", ...
        "prev + trajectory init", params);
end

