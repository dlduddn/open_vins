function [rawResults, summaryResults] = runPfModuleAblation(mode, nParticles, pfSeeds, mapSeeds)
%RUNPFMODULEABLATION Full-trajectory module/rule ablation runner.
%
% Examples:
%   runPfModuleAblation("smoke")    % syntax/data-path validation
%   runPfModuleAblation("screen")   % 500 particles, 3 PF seeds
%   runPfModuleAblation("confirm")  % 1500 particles, 5 PF seeds
%   runPfModuleAblation("combo_particle_sweep") % requested minimal-combo sweep
%   runPfModuleAblation("motion_threshold_sweep") % yaw/pitch rejection tuning
%   runPfModuleAblation("gt_zero_screen") % zero map error, GT Bezier, no init alignment
%   runPfModuleAblation("gt_zero_confirm") % 1500-particle confirmation for gt_zero_screen

    if nargin < 1 || isempty(mode)
        mode = "screen";
    end
    mode = lower(string(mode));

    addpath estimator\ map\ math\ rosservice\ utils\

    baseCfg = loadConfig();
    baseCfg.yamlLogProgress = false;
    baseCfg.pfLogProgress = false;
    baseCfg.pfVisualizeMapMatching = false;
    baseCfg = applyModeBaseConfig(baseCfg, mode);

    if nargin < 2 || isempty(nParticles)
        nParticles = defaultParticleCount(mode);
    end
    nParticleList = nParticles(:).';
    if nargin < 3 || isempty(pfSeeds)
        pfSeeds = defaultPfSeeds(mode);
    end
    if nargin < 4 || isempty(mapSeeds)
        mapSeeds = defaultMapSeeds(mode, baseCfg);
    end

    variants = makeVariants(mode);
    outDir = fullfile(fileparts(mfilename('fullpath')), 'ablation_logs');
    if ~exist(outDir, 'dir')
        mkdir(outDir);
    end

    fprintf('PF module ablation mode=%s, particleCounts=[%s], pfSeeds=[%s], mapSeeds=[%s], variants=%d\n', ...
        mode, num2str(nParticleList), num2str(pfSeeds), num2str(mapSeeds), numel(variants));

    rows = repmat(emptyResultRow(), 0, 1);
    runStart = tic;

    for iMap = 1:numel(mapSeeds)
        mapSeed = mapSeeds(iMap);
        cfgMap = applyMapInitSeed(baseCfg, mapSeed);
        data = loadExperimentData(cfgMap);

        for iVariant = 1:numel(variants)
            variant = variants(iVariant);
            cfgVariant = applyParams(cfgMap, variant.params);
            cfgVariant.ablationTag = variant.name;
            cfgVariant.ablationNotes = variant.description;

            fprintf('\n[%d/%d map %d/%d] %s | %s\n', ...
                iVariant, numel(variants), iMap, numel(mapSeeds), ...
                variant.name, variant.description);

            stats = countBezierDatasetStats(cfgVariant, data.queryBezier);
            [x0, x0Align, alignInfo, alignElapsedSec] = computeInitialState(cfgVariant, data);
            p0 = initialCovariance(cfgVariant);

            for iParticle = 1:numel(nParticleList)
                for iSeed = 1:numel(pfSeeds)
                    cfg = cfgVariant;
                    cfg.pfNumParticles = nParticleList(iParticle);
                    cfg.pfRandomSeed = pfSeeds(iSeed);
                    fprintf('  seed=%d, N=%d ... ', cfg.pfRandomSeed, cfg.pfNumParticles);

                    elapsedTimer = tic;
                    [xhat, nEff, pfDiag] = sir(cfg, data.mapDB, x0, p0, ...
                        data.dSE2, data.queryBezier, [], data.len, cfg.pfNumParticles);
                    elapsedSec = toc(elapsedTimer);

                    xhatGt = recenterStatesByPose(xhat, data.xTrue0InMap);
                    metrics = evaluateTrajectories(data.gtXY, data.vioXY, xhatGt(1:2, :));
                    diagSummary = summarizePfDiag(pfDiag, nEff, cfg.pfNumParticles);

                    row = emptyResultRow();
                    row.mode = mode;
                    row.variantName = variant.name;
                    row.stage = variant.stage;
                    row.description = variant.description;
                    row.moduleSet = variant.moduleSet;
                    row.nParticles = cfg.pfNumParticles;
                    row.pfSeed = cfg.pfRandomSeed;
                    row.mapSeed = mapSeed;
                    row.nSamples = metrics.n;
                    row.vioRmse = metrics.vio.rmse;
                    row.pfRmse = metrics.pf.rmse;
                    row.improvement = metrics.rmseImprovement;
                    row.improvementPct = metrics.rmseImprovementPct;
                    row.beatsVio = metrics.pf.rmse < metrics.vio.rmse;
                    row.vioMeanError = metrics.vio.mean;
                    row.pfMeanError = metrics.pf.mean;
                    row.vioFinalError = metrics.vio.final;
                    row.pfFinalError = metrics.pf.final;
                    row.pfAxisRmseX = metrics.pf.axisRmse(1);
                    row.pfAxisRmseY = metrics.pf.axisRmse(2);
                    row.alignElapsedSec = alignElapsedSec;
                    row.alignX = x0Align(1);
                    row.alignY = x0Align(2);
                    row.alignYawDeg = rad2deg(x0Align(3));
                    row.alignLogLikelihood = getStructScalar(alignInfo, 'logLikelihood', NaN);
                    row.alignSelectedFrames = selectedFrameCount(alignInfo);
                    row.usableFrames = stats.usableFrames;
                    row.usableCurves = stats.usableCurves;
                    row.rejectYawing = stats.rejectYawing;
                    row.rejectPitching = stats.rejectPitching;
                    row.rejectShortChord = stats.rejectShortChord;
                    row.rejectNearBody = stats.rejectNearBody;
                    row.rejectIsolatedStart = stats.rejectIsolatedStart;
                    row.usedUpdateFrames = diagSummary.usedUpdateFrames;
                    row.resampleCount = diagSummary.resampleCount;
                    row.meanNeffRatio = diagSummary.meanNeffRatio;
                    row.stdNeffRatio = diagSummary.stdNeffRatio;
                    row.meanAssociatedParticleRatio = diagSummary.meanAssociatedParticleRatio;
                    row.meanRoadGatePassRatio = diagSummary.meanRoadGatePassRatio;
                    row.meanMatchedCurveCount = diagSummary.meanMatchedCurveCount;
                    row.meanResidual = diagSummary.meanResidual;
                    row.elapsedSec = elapsedSec;

                    rows(end + 1) = row; %#ok<AGROW>
                    fprintf('PF RMSE=%.3f, VIO RMSE=%.3f, improvement=%.2f%%, N_eff=%.2f, %.1fs\n', ...
                        row.pfRmse, row.vioRmse, row.improvementPct, row.meanNeffRatio, elapsedSec);
                end
            end
        end
    end

    rawResults = struct2table(rows);
    summaryResults = summarizeResults(rawResults);

    timestamp = char(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));
    rawPath = fullfile(outDir, sprintf('pf_module_ablation_%s_raw_%s.csv', mode, timestamp));
    summaryPath = fullfile(outDir, sprintf('pf_module_ablation_%s_summary_%s.csv', mode, timestamp));
    writetable(rawResults, rawPath);
    writetable(summaryResults, summaryPath);

    latestRawPath = fullfile(outDir, sprintf('pf_module_ablation_%s_raw_latest.csv', mode));
    latestSummaryPath = fullfile(outDir, sprintf('pf_module_ablation_%s_summary_latest.csv', mode));
    writetable(rawResults, latestRawPath);
    writetable(summaryResults, latestSummaryPath);

    fprintf('\nSaved raw results: %s\n', rawPath);
    fprintf('Saved summary    : %s\n', summaryPath);
    fprintf('Total elapsed    : %.1f sec\n', toc(runStart));
    disp(summaryResults);
end

function cfg = applyModeBaseConfig(cfg, mode)
    if ~startsWith(mode, "gt_zero")
        return;
    end

    % Requested GT-query / zero-map-error condition. Initial alignment is
    % intentionally disabled because the map and query frames start aligned.
    cfg.yamlDir = 'D:\Comple Urban\Urban26\stereo_left_bezier_gt';
    cfg.mapInitErrorSeed = NaN;
    cfg.mapInitXError = 0.0;
    cfg.mapInitYError = 0.0;
    cfg.mapInitYawError = 0.0;
    cfg.initUse = false;
    cfg.initUseTrajectoryAlignment = false;
    cfg.initUseLongitudinalCorrection = false;
    cfg.pfInitXStd = 0.0;
    cfg.pfInitYStd = 0.0;
    cfg.pfInitYawStdDeg = 0.0;

    % Use a canonical full-module baseline for this ablation mode so that
    % one-at-a-time/backward variants still mean "remove from full".
    cfg.pfProcessNoiseFrame = 'body';
    cfg.pfUseMeasurementUpdate = true;
    cfg.pfLikelihoodTemperature = 6.0;
    cfg.pfLikelihoodMaxLogSpan = 22.0;
    cfg.pfWeightUniformMix = 0.02;
    cfg.pfMinAssociatedParticleRatio = 0.02;
    cfg.pfRoughenAfterResample = true;

    cfg.assocUseYawingRejection = true;
    cfg.assocUsePitchingRejection = true;
    cfg.assocUseMinCurveChordRule = true;
    cfg.assocUseMinBodyDistanceRule = true;
    cfg.assocUseStartConnectionRule = true;
    cfg.assocRequireStartConnection = false;
    cfg.assocAllowSingleCurveWithoutConnection = true;
    cfg.assocUseBodyRoadGate = true;
    cfg.assocUseCurveMapCorrespondenceRule = true;
    cfg.assocUseCameraFovGate = true;

    cfg.likelihoodUseRobust = true;
    cfg.likelihoodMaxEffectiveSamples = 12;
    cfg.likelihoodInlierReward = 0.75;
end

function nParticles = defaultParticleCount(mode)
    if mode == "combo_particle_sweep"
        nParticles = [10, 100, 500, 1500];
    elseif mode == "motion_threshold_sweep"
        nParticles = 500;
    elseif mode == "gt_zero_confirm"
        nParticles = 1500;
    elseif mode == "confirm"
        nParticles = 1500;
    elseif mode == "smoke"
        nParticles = 100;
    else
        nParticles = 500;
    end
end

function seeds = defaultPfSeeds(mode)
    if mode == "confirm" || mode == "combo_particle_sweep" || ...
            mode == "motion_threshold_sweep" || mode == "gt_zero_confirm"
        seeds = [7, 11, 13, 17, 19];
    elseif mode == "smoke"
        seeds = 7;
    else
        seeds = [7, 11, 13];
    end
end

function mapSeeds = defaultMapSeeds(mode, baseCfg)
    if startsWith(mode, "gt_zero")
        mapSeeds = NaN;
    else
        mapSeeds = getScalar(baseCfg, 'mapInitErrorSeed', 7);
    end
end

function variants = makeVariants(mode)
    variants = allVariants();
    if mode == "smoke"
        keep = ["pf_minimal", "pf_full", "no_measurement_update"];
        variants = variants(ismember([variants.name], keep));
    elseif mode == "confirm"
        keep = ["pf_full", "map_frame_process_noise", "back_no_pf_stabilization", ...
            "ix_no_fov_wide_assoc", "no_inlier_reward", "no_body_road_gate", ...
            "ix_no_geometry_query_rules", "back_no_query_rules", "back_no_map_gates", ...
            "fwd_07_query_rules", "fwd_09_trajectory_init", ...
            "gaussian_likelihood", "back_no_likelihood_shaping"];
        variants = variants(ismember([variants.name], keep));
    elseif mode == "combo_particle_sweep"
        keep = "combo_map_noise_no_query_no_body_road";
        variants = variants(ismember([variants.name], keep));
    elseif mode == "motion_threshold_sweep"
        variants = motionThresholdVariants();
    elseif mode == "gt_zero_screen"
        keep = gtZeroScreenKeepList();
        variants = variants(ismember([variants.name], keep));
    elseif mode == "gt_zero_confirm"
        keep = ["pf_minimal", "pf_full", "no_measurement_update", ...
            "fwd_02_measurement_basic", "fwd_07_query_rules", ...
            "back_no_pf_stabilization", "ix_no_robust_no_temp_clip", ...
            "no_likelihood_temperature", "no_weight_uniform_mix", ...
            "no_adaptive_process_scale", "no_effective_sample_cap", ...
            "map_frame_process_noise", "combo_map_noise_no_query_no_body_road", ...
            "back_no_query_rules", "back_no_map_gates", ...
            "gaussian_likelihood", "back_no_likelihood_shaping", ...
            "strict_start_connection"];
        variants = variants(ismember([variants.name], keep));
    end
end

