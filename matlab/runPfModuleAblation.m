end

function summaryTable = summarizeResults(rawResults)
    keys = unique(rawResults(:, {'variantName', 'nParticles'}), 'rows', 'stable');
    rows = repmat(emptySummaryRow(), 0, 1);
    for i = 1:height(keys)
        mask = rawResults.variantName == keys.variantName(i) & ...
            rawResults.nParticles == keys.nParticles(i);
        subset = rawResults(mask, :);
        row = emptySummaryRow();
        row.variantName = keys.variantName(i);
        row.stage = subset.stage(1);
        row.description = subset.description(1);
        row.moduleSet = subset.moduleSet(1);
        row.nRuns = height(subset);
        row.nParticles = subset.nParticles(1);
        row.meanVioRmse = mean(subset.vioRmse, 'omitnan');
        row.meanPfRmse = mean(subset.pfRmse, 'omitnan');
        row.stdPfRmse = std(subset.pfRmse, 0, 'omitnan');
        row.meanImprovement = mean(subset.improvement, 'omitnan');
        row.meanImprovementPct = mean(subset.improvementPct, 'omitnan');
        row.stdImprovementPct = std(subset.improvementPct, 0, 'omitnan');
        row.worstImprovementPct = min(subset.improvementPct);
        row.bestImprovementPct = max(subset.improvementPct);
        row.beatsVioRate = mean(double(subset.beatsVio), 'omitnan');
        row.meanNeffRatio = mean(subset.meanNeffRatio, 'omitnan');
        row.meanAssociatedParticleRatio = mean(subset.meanAssociatedParticleRatio, 'omitnan');
        row.meanRoadGatePassRatio = mean(subset.meanRoadGatePassRatio, 'omitnan');
        row.meanResidual = mean(subset.meanResidual, 'omitnan');
        row.meanElapsedSec = mean(subset.elapsedSec, 'omitnan');
        rows(end + 1) = row; %#ok<AGROW>
    end
    summaryTable = struct2table(rows);
    if height(unique(summaryTable(:, 'variantName'), 'rows')) == 1
        summaryTable = sortrows(summaryTable, 'nParticles');
    else
        summaryTable = sortrows(summaryTable, 'meanPfRmse');
    end
end

