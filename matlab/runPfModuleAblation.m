function stats = countBezierDatasetStats(cfg, meas)
    stats = struct('usableFrames', 0, 'usableCurves', 0, ...
        'rejectYawing', 0, 'rejectPitching', 0, 'rejectShortChord', 0, ...
        'rejectNearBody', 0, 'rejectIsolatedStart', 0);
    for k = 1:numel(meas)
        frame = buildQueryBezierFrame(cfg, meas(k));
        if frame.hasUsableCurves
            stats.usableFrames = stats.usableFrames + 1;
            stats.usableCurves = stats.usableCurves + numel(frame.usableIdx);
        end
        if isfield(frame, 'rejectSummary')
            stats.rejectYawing = stats.rejectYawing + getRejectCount(frame.rejectSummary, 'yawing');
            stats.rejectPitching = stats.rejectPitching + getRejectCount(frame.rejectSummary, 'pitching');
            stats.rejectShortChord = stats.rejectShortChord + getRejectCount(frame.rejectSummary, 'shortChord');
            stats.rejectNearBody = stats.rejectNearBody + getRejectCount(frame.rejectSummary, 'nearBody');
            stats.rejectIsolatedStart = stats.rejectIsolatedStart + getRejectCount(frame.rejectSummary, 'isolatedStart');
        end
    end
end

